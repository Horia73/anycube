//! Exact 3x3x3 distance to the subgroup "corners untwisted, edges unflipped,
//! the four slice edges in place": 2187 x 2048 x 11880 = 53 billion cosets,
//! reduced eightfold by the rotations that keep the U/D axis and stored
//! modulo 3 in two bits each (about 1.7 GB).
//!
//! It is a much sharper lower bound for the exact 3x3x3 search than the
//! distance to the domino subgroup: about one move more on average, along
//! each of the three axes.

use crate::c3::{perm_rank, perm_unrank, C3, T3, N_FLIP, N_SLICE, N_TWIST};
use crate::cube::tables as cube_tables;
use crate::tables::{load_or_gen, table_dir, Bytes};
use rayon::prelude::*;
use std::sync::atomic::{AtomicU8, Ordering::Relaxed};

/// Arrangements of the four slice edges over the twelve positions.
pub const N_SS: usize = N_SLICE * 24;
const N_SYM: usize = 8;

pub struct Big2 {
    data: Bytes,
    pub ss_mv: Vec<[u16; 18]>,
    /// Per arrangement: (class, symmetry that maps it to the class representative).
    ss_class: Vec<(u16, u8)>,
    /// Class representative and the symmetries that fix it (bit mask).
    rep: Vec<u16>,
    stab: Vec<u8>,
    /// Flip under a symmetry: the bits permute, plus a mask that depends on the slice.
    flip_perm: Vec<Vec<u16>>,
    flip_mask: Vec<Vec<u16>>,
    twist_conj: Vec<[u16; N_SYM]>,
}

fn ss_of(t: &T3, c: &C3) -> usize {
    let mut p = [0u8; 4];
    let mut n = 0;
    for i in 0..12 {
        if c.ep[i] >= 8 {
            p[n] = c.ep[i] - 8;
            n += 1;
        }
    }
    t.slice_rank[c.slice_mask()] as usize * 24 + perm_rank(&p)
}

fn ss_cube(t: &T3, ss: usize) -> C3 {
    let mut c = C3::identity();
    let mut p = [0u8; 4];
    perm_unrank(ss % 24, &mut p);
    let mask = t.slice_unrank[ss / 24];
    let (mut hi, mut lo) = (0, 0u8);
    for i in 0..12 {
        if (mask >> i) & 1 == 1 {
            c.ep[i] = p[hi] + 8;
            hi += 1;
        } else {
            c.ep[i] = lo;
            lo += 1;
        }
    }
    c
}

fn twist_cube(tw: usize) -> C3 {
    let mut c = C3::identity();
    let (mut x, mut sum) = (tw, 0);
    for i in (0..7).rev() {
        c.co[i] = (x % 3) as u8;
        sum += x % 3;
        x /= 3;
    }
    c.co[7] = ((15 - sum) % 3) as u8;
    c
}

fn flip_cube(fl: usize) -> C3 {
    let mut c = C3::identity();
    for i in 0..11 {
        c.eo[i] = ((fl >> i) & 1) as u8;
    }
    c.eo[11] = (fl.count_ones() & 1) as u8;
    c
}

#[inline(always)]
fn get(bytes: &[AtomicU8], idx: usize) -> u8 {
    (bytes[idx >> 2].load(Relaxed) >> ((idx & 3) * 2)) & 3
}

/// Sets an unvisited entry (3) to `v`; returns true if this call did it.
#[inline(always)]
fn set(bytes: &[AtomicU8], idx: usize, v: u8) -> bool {
    let shift = (idx & 3) * 2;
    let cell = &bytes[idx >> 2];
    let mut cur = cell.load(Relaxed);
    loop {
        if (cur >> shift) & 3 != 3 {
            return false;
        }
        match cell.compare_exchange_weak(cur, cur & !((3 ^ v) << shift), Relaxed, Relaxed) {
            Ok(_) => return true,
            Err(now) => cur = now,
        }
    }
}

impl Big2 {
    pub fn load(t: &T3) -> Big2 {
        let ct = cube_tables();
        // The eight rotations that keep the U/D axis: generated by y and x2.
        let gens: [&[u8]; 2] = [&[18, 29], &[21, 32, 21, 32]];
        let mut seqs: Vec<Vec<u8>> = vec![vec![]];
        let mut ids = vec![0usize];
        let mut i = 0;
        while i < seqs.len() {
            for g in gens {
                let mut s = seqs[i].clone();
                s.extend_from_slice(g);
                let r = ct.rot_index(&s);
                if !ids.contains(&r) {
                    ids.push(r);
                    seqs.push(s);
                }
            }
            i += 1;
        }
        assert_eq!(ids.len(), N_SYM);
        let rots: Vec<C3> = ids.iter().map(|&r| C3::from_cube(&ct.rots[r].state).unwrap()).collect();
        let invs: Vec<C3> = rots.iter().map(|r| r.inverse()).collect();
        let conj = |k: usize, c: &C3| invs[k].mul(c).mul(&rots[k]);
        let inv_sym: Vec<usize> =
            (0..N_SYM).map(|k| rots.iter().position(|r| *r == invs[k]).unwrap()).collect();

        let mut ss_mv = vec![[0u16; 18]; N_SS];
        let mut ss_conj = vec![[0u16; N_SYM]; N_SS];
        for ss in 0..N_SS {
            let c = ss_cube(t, ss);
            debug_assert_eq!(ss_of(t, &c), ss);
            for m in 0..18 {
                ss_mv[ss][m] = ss_of(t, &c.mul(&t.moves[m])) as u16;
            }
            for k in 0..N_SYM {
                ss_conj[ss][k] = ss_of(t, &conj(k, &c)) as u16;
            }
        }
        let mut twist_conj = vec![[0u16; N_SYM]; N_TWIST];
        for tw in 0..N_TWIST {
            for k in 0..N_SYM {
                twist_conj[tw][k] = conj(k, &twist_cube(tw)).twist() as u16;
            }
        }
        let mut flip_perm = vec![vec![0u16; N_FLIP]; N_SYM];
        let mut flip_mask = vec![vec![0u16; N_SLICE]; N_SYM];
        for k in 0..N_SYM {
            for fl in 0..N_FLIP {
                flip_perm[k][fl] = conj(k, &flip_cube(fl)).flip() as u16;
            }
            for sl in 0..N_SLICE {
                flip_mask[k][sl] = conj(k, &ss_cube(t, sl * 24)).flip() as u16;
            }
        }
        // Classes of slice arrangements.
        let mut ss_class = vec![(u16::MAX, 0u8); N_SS];
        let mut rep = Vec::new();
        let mut stab = Vec::new();
        for ss in 0..N_SS {
            if ss_class[ss].0 != u16::MAX {
                continue;
            }
            let c = rep.len() as u16;
            let mut fixed = 0u8;
            for k in 0..N_SYM {
                let image = ss_conj[ss][k] as usize;
                if image == ss {
                    fixed |= 1 << k;
                }
                if ss_class[image].0 == u16::MAX {
                    ss_class[image] = (c, inv_sym[k] as u8);
                }
            }
            rep.push(ss as u16);
            stab.push(fixed);
        }
        let mut b = Big2 {
            data: Bytes::Owned(Vec::new()),
            ss_mv,
            ss_class,
            rep,
            stab,
            flip_perm,
            flip_mask,
            twist_conj,
        };
        // The decomposition of the symmetries must agree with the real thing.
        let mut seed = 1u64;
        for _ in 0..2000 {
            seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            let (tw, fl, ss) =
                ((seed >> 20) as usize % N_TWIST, (seed >> 34) as usize % N_FLIP, (seed >> 46) as usize % N_SS);
            let k = (seed >> 60) as usize % N_SYM;
            let mut c = ss_cube(t, ss);
            c.co = twist_cube(tw).co;
            c.eo = flip_cube(fl).eo;
            let d = conj(k, &c);
            assert_eq!(d.twist(), b.twist_conj[tw][k] as usize);
            assert_eq!(d.flip(), (b.flip_perm[k][fl] ^ b.flip_mask[k][ss / 24]) as usize);
            assert_eq!(ss_of(t, &d), ss_conj[ss][k] as usize);
            let (cl, kk) = b.ss_class[ss];
            assert_eq!(ss_conj[ss][kk as usize], b.rep[cl as usize]);
        }
        let n = b.len();
        let path = table_dir().join("slice-exact.bin");
        b.data = load_or_gen(&path, n.div_ceil(4), || b.generate(t));
        b
    }

    fn len(&self) -> usize {
        self.rep.len() * N_FLIP * N_TWIST
    }

    pub fn ss(&self, t: &T3, c: &C3) -> usize {
        ss_of(t, c)
    }

    #[inline(always)]
    pub fn index(&self, tw: usize, fl: usize, ss: usize) -> usize {
        let (c, k) = self.ss_class[ss];
        let k = k as usize;
        let fl = (self.flip_perm[k][fl] ^ self.flip_mask[k][ss / 24]) as usize;
        (c as usize * N_FLIP + fl) * N_TWIST + self.twist_conj[tw][k] as usize
    }

    /// Distance modulo 3.
    #[inline(always)]
    pub fn get(&self, idx: usize) -> u8 {
        (self.data[idx >> 2] >> ((idx & 3) * 2)) & 3
    }

    fn generate(&self, t: &T3) -> Vec<u8> {
        let n = self.len();
        let bytes: Vec<AtomicU8> = {
            let mut v = vec![0xFFu8; n.div_ceil(4)];
            let p = v.as_mut_ptr() as *mut AtomicU8;
            let (len, cap) = (v.len(), v.capacity());
            std::mem::forget(v);
            // AtomicU8 has the same layout as u8.
            unsafe { Vec::from_raw_parts(p, len, cap) }
        };
        // Sets an entry and its images under the symmetries that fix its class.
        // Calls `on_new` for every entry this call set.
        let set_all = |idx: usize, v: u8, on_new: &mut dyn FnMut(usize)| {
            if set(&bytes, idx, v) {
                on_new(idx);
            }
            let c = idx / (N_FLIP * N_TWIST);
            if self.stab[c] != 1 {
                let (fl, tw) = (idx / N_TWIST % N_FLIP, idx % N_TWIST);
                let sl = self.rep[c] as usize / 24;
                for k in 1..N_SYM {
                    if (self.stab[c] >> k) & 1 == 1 {
                        let fl2 = (self.flip_perm[k][fl] ^ self.flip_mask[k][sl]) as usize;
                        let other = (c * N_FLIP + fl2) * N_TWIST + self.twist_conj[tw][k] as usize;
                        if set(&bytes, other, v) {
                            on_new(other);
                        }
                    }
                }
            }
        };
        let goal_ss = ss_of(t, &C3::identity());
        let goal = self.index(0, 0, goal_ss);
        let mut done = 0u64;
        let mut frontier: Vec<u64> = Vec::new();
        set_all(goal, 0, &mut |i| frontier.push(i as u64));
        done += frontier.len() as u64;
        let mut depth = 0usize;
        // Push from explicit frontiers while they are small.
        while !frontier.is_empty() {
            let v = ((depth + 1) % 3) as u8;
            let keep = frontier.len() <= 3_000_000;
            let next: Vec<(Vec<u64>, u64)> = frontier
                .par_chunks(4096)
                .map(|chunk| {
                    let mut out = Vec::new();
                    let mut cnt = 0u64;
                    for &x in chunk {
                        let x = x as usize;
                        let (c, fl, tw) = (x / (N_FLIP * N_TWIST), x / N_TWIST % N_FLIP, x % N_TWIST);
                        let ss = self.rep[c] as usize;
                        for m in 0..18 {
                            let y = self.index(
                                t.twist_mv[tw][m] as usize,
                                t.flip_mv[fl][m] as usize,
                                self.ss_mv[ss][m] as usize,
                            );
                            set_all(y, v, &mut |i| {
                                cnt += 1;
                                if keep {
                                    out.push(i as u64);
                                }
                            });
                        }
                    }
                    (out, cnt)
                })
                .collect();
            let cnt: u64 = next.iter().map(|p| p.1).sum();
            frontier = next.into_iter().flat_map(|p| p.0).collect();
            depth += 1;
            done += cnt;
            eprintln!("  slice table: depth {:2}  {:>11} new  {:>11} total", depth, cnt, done);
            if !keep {
                break;
            }
        }
        drop(frontier);
        // Then pull: every unvisited state looks for a neighbour at the current depth.
        while done < n as u64 {
            let target = (depth % 3) as u8;
            let v = ((depth + 1) % 3) as u8;
            let cnt: u64 = (0..self.rep.len() * N_FLIP)
                .into_par_iter()
                .with_min_len(64)
                .map(|b| {
                    let base = b * N_TWIST;
                    let mut unv: Vec<u16> = Vec::new();
                    for tw in 0..N_TWIST {
                        if get(&bytes, base + tw) == 3 {
                            unv.push(tw as u16);
                        }
                    }
                    if unv.is_empty() {
                        return 0;
                    }
                    let (c, fl) = (b / N_FLIP, b % N_FLIP);
                    let ss = self.rep[c] as usize;
                    let mut found = 0u64;
                    for m in 0..18 {
                        let ss2 = self.ss_mv[ss][m] as usize;
                        let (c2, k) = self.ss_class[ss2];
                        let k = k as usize;
                        let fl2 = (self.flip_perm[k][t.flip_mv[fl][m] as usize] ^ self.flip_mask[k][ss2 / 24]) as usize;
                        let nb = (c2 as usize * N_FLIP + fl2) * N_TWIST;
                        let mut i = 0;
                        while i < unv.len() {
                            let tw = unv[i] as usize;
                            let tw2 = self.twist_conj[t.twist_mv[tw][m] as usize][k] as usize;
                            if get(&bytes, nb + tw2) == target {
                                set(&bytes, base + tw, v);
                                found += 1;
                                unv.swap_remove(i);
                            } else {
                                i += 1;
                            }
                        }
                        if unv.is_empty() {
                            break;
                        }
                    }
                    found
                })
                .sum();
            assert!(cnt > 0, "slice table: unreachable states remain");
            depth += 1;
            done += cnt;
            eprintln!("  slice table: depth {:2}  {:>11} new  {:>11} total", depth, cnt, done);
        }
        let mut v = std::mem::ManuallyDrop::new(bytes);
        unsafe { Vec::from_raw_parts(v.as_mut_ptr() as *mut u8, v.len(), v.capacity()) }
    }

    /// Exact distance, found by walking down to the goal.
    pub fn exact(&self, t: &T3, mut tw: usize, mut fl: usize, mut ss: usize) -> u8 {
        let goal = self.index(0, 0, ss_of(t, &C3::identity()));
        let mut d = 0u8;
        let mut cur = self.get(self.index(tw, fl, ss));
        while self.index(tw, fl, ss) != goal {
            let want = (cur + 2) % 3;
            let mut moved = false;
            for m in 0..18 {
                let (a, b, c) =
                    (t.twist_mv[tw][m] as usize, t.flip_mv[fl][m] as usize, self.ss_mv[ss][m] as usize);
                if self.get(self.index(a, b, c)) == want {
                    (tw, fl, ss) = (a, b, c);
                    cur = want;
                    d += 1;
                    moved = true;
                    break;
                }
            }
            assert!(moved, "corrupt slice table");
        }
        d
    }
}
