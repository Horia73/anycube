//! Symmetries of the cube as they act on search coordinates.
//!
//! A symmetry renames the moves (`mu`). A coordinate has that symmetry if
//! there is a map `p` of its values with `p(move(x)) == mu(move)(p(x))`: then
//! `x` and `p(x)` are equally far from any goal that `p` keeps in place, and
//! a distance table needs one entry for the two of them. The maps are found
//! by search from the move tables, not from geometry, so they also include
//! symmetries of a coordinate that are not symmetries of the whole cube.

use crate::c5::tables5;

/// Move renamings that keep the R/L axis: none, a quarter turn of the whole
/// cube about that axis, a half turn about the U/D axis, and the mirror
/// image left to right.
pub fn axis_move_maps() -> Vec<[u8; 36]> {
    let g = &tables5().geometry;
    let to_array = |v: Vec<usize>| {
        let mut a = [0u8; 36];
        for (m, &x) in v.iter().enumerate() {
            a[m] = x as u8;
        }
        a
    };
    let mut mirror = [0u8; 36];
    for m in 0..36 {
        let (face, layer, power) = (m / 3 % 6, m / 18, m % 3);
        let face = match face {
            1 => 4,
            4 => 1,
            f => f,
        };
        mirror[m] = ((face + 6 * layer) * 3 + (2 - power)) as u8;
    }
    vec![to_array((0..36).collect()), to_array(g.frame_moves(&[0])), to_array(g.frame_moves(&[1, 1])), mirror]
}

/// Every permutation `p` of `0..n` with `p(act_a(a, x)) == act_b(b, p(x))`
/// for each pair of moves `(a, b)`, and with `p(x) == y` for each pair in
/// `fixed`. With one action and a renaming of its moves these are the
/// symmetries of a coordinate; with two actions they are the ways to number
/// one set of pieces like another.
pub fn conjugators(
    n: usize,
    pairs: &[(usize, usize)],
    act_a: &dyn Fn(usize, usize) -> usize,
    act_b: &dyn Fn(usize, usize) -> usize,
    fixed: &[(usize, usize)],
) -> Vec<Vec<u32>> {
    const NONE: u32 = u32::MAX;
    struct Ctx<'a> {
        pairs: &'a [(usize, usize)],
        act_a: &'a dyn Fn(usize, usize) -> usize,
        act_b: &'a dyn Fn(usize, usize) -> usize,
    }
    // Sets p(x) = y and everything that follows from it; false on a contradiction.
    fn assign(c: &Ctx, p: &mut [u32], used: &mut [bool], x: usize, y: usize) -> bool {
        let mut queue = vec![(x, y)];
        while let Some((x, y)) = queue.pop() {
            if p[x] != NONE {
                if p[x] as usize != y {
                    return false;
                }
                continue;
            }
            if used[y] {
                return false;
            }
            p[x] = y as u32;
            used[y] = true;
            for &(a, b) in c.pairs {
                queue.push(((c.act_a)(a, x), (c.act_b)(b, y)));
            }
        }
        true
    }
    fn extend(c: &Ctx, p: Vec<u32>, used: Vec<bool>, out: &mut Vec<Vec<u32>>) {
        let Some(x) = p.iter().position(|&v| v == NONE) else {
            out.push(p);
            return;
        };
        for y in 0..p.len() {
            if !used[y] {
                let (mut q, mut u) = (p.clone(), used.clone());
                if assign(c, &mut q, &mut u, x, y) {
                    extend(c, q, u, out);
                }
            }
        }
    }
    let c = Ctx { pairs, act_a, act_b };
    let (mut p, mut used) = (vec![NONE; n], vec![false; n]);
    for &(x, y) in fixed {
        if !assign(&c, &mut p, &mut used, x, y) {
            return Vec::new();
        }
    }
    let mut out = Vec::new();
    extend(&c, p, used, &mut out);
    out
}

/// The pairs (move, renamed move) for a list of moves.
pub fn renamed(moves: &[u8], mu: &[u8; 36]) -> Vec<(usize, usize)> {
    moves.iter().map(|&m| (m as usize, mu[m as usize] as usize)).collect()
}

/// A symmetry as it acts on several sets of points at once.
pub type Element = Vec<Vec<u32>>;

/// The group generated by the given elements; the identity comes first.
pub fn closure(generators: &[Element]) -> Vec<Element> {
    let Some(first) = generators.first() else { return Vec::new() };
    let identity: Element = first.iter().map(|p| (0..p.len() as u32).collect()).collect();
    let mut group = vec![identity];
    let mut i = 0;
    while i < group.len() {
        for g in generators {
            let product: Element =
                g.iter().zip(&group[i]).map(|(a, b)| b.iter().map(|&x| a[x as usize]).collect()).collect();
            if !group.contains(&product) {
                group.push(product);
            }
        }
        i += 1;
        assert!(group.len() <= 64, "more symmetries than expected");
    }
    group
}

/// A permutation of 24 positions, applied to sets of positions given as bit masks.
#[derive(Clone)]
pub struct MaskMap {
    t: [[u32; 256]; 3],
}

impl MaskMap {
    /// `p[i]` is where position `i` goes.
    pub fn new(p: &[u32]) -> MaskMap {
        let mut t = [[0u32; 256]; 3];
        for k in 0..3 {
            for byte in 0..256usize {
                for j in 0..8 {
                    if (byte >> j) & 1 == 1 {
                        t[k][byte] |= 1 << p[8 * k + j];
                    }
                }
            }
        }
        MaskMap { t }
    }

    #[inline(always)]
    pub fn apply(&self, x: u32) -> u32 {
        self.t[0][(x & 255) as usize] | self.t[1][((x >> 8) & 255) as usize] | self.t[2][(x >> 16) as usize]
    }
}

/// Where each position goes under each move, from "where it comes from" tables.
pub fn destinations(src: &[[u8; 24]]) -> Vec<[u8; 24]> {
    src.iter()
        .map(|s| {
            let mut d = [0u8; 24];
            for i in 0..24 {
                d[s[i] as usize] = i as u8;
            }
            d
        })
        .collect()
}

/// Rank of a `k`-of-24 mask (colex), byte by byte, and the inverse.
pub struct CombRank {
    tab: Vec<[[u32; 13]; 256]>,
    pub unrank: Vec<u32>,
}

impl CombRank {
    pub fn new(k: usize) -> CombRank {
        assert!(k <= 12);
        let mut binom = [[0u64; 14]; 25];
        for n in 0..25 {
            binom[n][0] = 1;
            for j in 1..14.min(n + 1) {
                binom[n][j] = binom[n - 1][j - 1] + if j < n { binom[n - 1][j] } else { 0 };
            }
        }
        let mut tab = vec![[[0u32; 13]; 256]; 3];
        for part in 0..3 {
            for byte in 0..256usize {
                for below in 0..13usize {
                    let (mut r, mut i) = (0u64, below);
                    for j in 0..8 {
                        if (byte >> j) & 1 == 1 {
                            i += 1;
                            if i <= 13 {
                                r += binom[8 * part + j][i];
                            }
                        }
                    }
                    tab[part][byte][below] = r as u32;
                }
            }
        }
        let unrank: Vec<u32> = (0u32..1 << 24).filter(|x| x.count_ones() as usize == k).collect();
        let r = CombRank { tab, unrank };
        for i in [0, 1, r.unrank.len() / 3, r.unrank.len() - 1] {
            assert_eq!(r.rank(r.unrank[i]), i);
        }
        r
    }

    #[inline(always)]
    pub fn rank(&self, m: u32) -> usize {
        let (b0, b1, b2) = ((m & 255) as usize, ((m >> 8) & 255) as usize, (m >> 16) as usize);
        let c0 = b0.count_ones() as usize;
        let c1 = c0 + b1.count_ones() as usize;
        (self.tab[0][b0][0] + self.tab[1][b1][c0.min(12)] + self.tab[2][b2][c1.min(12)]) as usize
    }
}
